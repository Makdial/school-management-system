import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { fileURLToPath, URL } from 'node:url'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    port: 5173,
    // The SPA is same-origin in dev (API is proxied below), so Vite's own CORS
    // middleware is unnecessary — and it wrongly intercepts API OPTIONS
    // requests (returning 204) which we rely on for form metadata.
    cors: false,
    proxy: {
      // Proxy API calls to the Django backend so the SPA is same-origin in dev.
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
      '/media': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
    },
  },
})
